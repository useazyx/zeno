import { test, expect } from '@playwright/test'

test('following and comparison advance, pause, seek and release their controls', async ({ page }, info) => {
  test.setTimeout(120_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/rotas')
  const unit = page.locator('select').nth(1)
  const option = unit.locator('option', { hasText: 'PB-TAUBATE' })
  await expect(option).toBeAttached()
  await unit.selectOption((await option.getAttribute('value'))!)
  await page.getByRole('button', { name: 'Calcular rota', exact: true }).click()
  const follow = page.getByRole('button', { name: 'Seguir rota', exact: true })
  await expect(follow).toBeEnabled({ timeout: 60_000 })
  await follow.click()
  const hud = page.locator('.follow-hud')
  await expect(hud).toBeVisible()
  const clock = hud.locator('.simulation-timeline output')
  await expect.poll(() => clock.innerText()).not.toMatch(/^0:00 \/ /)
  await hud.getByRole('button', { name: 'Pausar', exact: true }).click()
  const paused = await clock.innerText()
  await page.waitForTimeout(400)
  await expect(clock).toHaveText(paused)
  await hud.getByRole('button', { name: 'Chegada', exact: true }).click()
  const progress = hud.getByRole('slider', { name: 'Tempo do percurso' })
  expect(Math.abs(Number(await progress.inputValue()) - Number(await progress.getAttribute('max')))).toBeLessThanOrEqual(Number(await progress.getAttribute('step')))
  const [elapsed, total] = (await clock.innerText()).split(' / ')
  expect(elapsed).toBe(total)
  await page.locator('.map-wrap').first().screenshot({ path: info.outputPath('follow.png') })
  await hud.getByRole('button', { name: 'Encerrar', exact: true }).click()
  await expect(hud).toHaveCount(0)
  await page.getByRole('button', { name: 'Comparar viaturas', exact: true }).click()
  const comparison = page.getByRole('region', { name: 'Simulação comparativa de deslocamento' })
  await expect(comparison).toBeVisible()
  const comparisonClock = comparison.locator('.simulation-timeline output')
  await expect.poll(() => comparisonClock.innerText()).not.toMatch(/^0:00 \/ /)
  await comparison.getByRole('button', { name: 'Pausar simulação', exact: true }).click()
  const comparisonPaused = await comparisonClock.innerText()
  await page.waitForTimeout(400)
  await expect(comparisonClock).toHaveText(comparisonPaused)
  await page.locator('.map-wrap').first().screenshot({ path: info.outputPath('comparison.png') })
  await comparison.getByRole('button', { name: 'Encerrar simulação e liberar a câmera', exact: true }).click()
  await expect(comparison).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  expect(errors).toEqual([])
})
